PACKAGES = ["cryptography", "liboqs-python", "numpy"]


def install_packages():
    """Install the Python libraries (replaces the notebook's !pip cell)."""
    print("Installing:", ", ".join(PACKAGES))
    subprocess.run(
        [sys.executable, "-m", "pip", "install", "-q", *PACKAGES],
        check=True,
    )


def import_libraries():
    """Import everything the experiments need, with a clear message if missing."""
    global np, x25519, rsa, padding, ed25519, hashes, AESGCM, HKDF, oqs
    try:
        import numpy as np
        from cryptography.hazmat.primitives import hashes
        from cryptography.hazmat.primitives.asymmetric import (
            ed25519,
            padding,
            rsa,
            x25519,
        )
        from cryptography.hazmat.primitives.ciphers.aead import AESGCM
        from cryptography.hazmat.primitives.kdf.hkdf import HKDF
        import oqs
    except ImportError as error:
        print("Missing library:", error)
        print("Install it with:  pip install", " ".join(PACKAGES))
        print("Or run this script with --install")
        sys.exit(1)
    print("liboqs version:", oqs.oqs_version())


# ---------------------------------------------------------------------------
# Timing helper
# ---------------------------------------------------------------------------

def median_time_us(function, runs=1000):
    """Run a function many times and return the median time in microseconds."""
    function()                                   # warm-up run
    times = []
    for _ in range(runs):
        start = time.perf_counter()
        function()
        times.append((time.perf_counter() - start) * 1e6)
    return statistics.median(times)


# ---------------------------------------------------------------------------
# 1. Cost of one key exchange
#    One full exchange = both sides (client and server) compute the shared secret.
# ---------------------------------------------------------------------------

def section_1_key_exchange(runs=1000):
    print("\n" + "=" * 62)
    print("1. Cost of one key exchange")
    print("=" * 62)

    # Classical: X25519 (elliptic curve)
    def x25519_exchange():
        client = x25519.X25519PrivateKey.generate()
        server = x25519.X25519PrivateKey.generate()
        secret_client = client.exchange(server.public_key())
        secret_server = server.exchange(client.public_key())
        assert secret_client == secret_server
        return secret_client

    # Classical: RSA-3072 (the server already has its key pair)
    rsa_key = rsa.generate_private_key(public_exponent=65537, key_size=3072)
    oaep = padding.OAEP(
        mgf=padding.MGF1(hashes.SHA256()),
        algorithm=hashes.SHA256(),
        label=None,
    )

    def rsa_exchange():
        secret = os.urandom(32)                                  # client chooses a secret
        ciphertext = rsa_key.public_key().encrypt(secret, oaep)   # encrypts it for the server
        return rsa_key.decrypt(ciphertext, oaep)                  # server decrypts it

    # Post-quantum: ML-KEM-768 (NIST FIPS 203)
    def mlkem_exchange():
        with oqs.KeyEncapsulation("ML-KEM-768") as client, \
             oqs.KeyEncapsulation("ML-KEM-768") as server:
            public_key = client.generate_keypair()                       # client sends its public key
            ciphertext, secret_server = server.encap_secret(public_key)  # server sends a ciphertext
            secret_client = client.decap_secret(ciphertext)              # client recovers the secret
            assert secret_client == secret_server
            return secret_client

    # Hybrid: X25519 + ML-KEM-768, both secrets mixed into one key
    def hybrid_exchange():
        s1 = x25519_exchange()
        s2 = mlkem_exchange()
        return HKDF(
            algorithm=hashes.SHA256(), length=32, salt=None, info=b"hybrid"
        ).derive(s1 + s2)

    with oqs.KeyEncapsulation("ML-KEM-768") as kem:
        mlkem = kem.details
    mlkem_bytes = mlkem["length_public_key"] + mlkem["length_ciphertext"]

    rsa_runs = max(1, runs // 3)                 # RSA is slow: fewer runs
    results = {
        "X25519":     (median_time_us(x25519_exchange, runs), 32 + 32),
        "RSA-3072":   (median_time_us(rsa_exchange, rsa_runs), 384 + 384),
        "ML-KEM-768": (median_time_us(mlkem_exchange, runs), mlkem_bytes),
        "Hybrid":     (median_time_us(hybrid_exchange, runs), 64 + mlkem_bytes),
    }
    print(f"{'Algorithm':<12}{'Time (us)':>12}{'Bytes sent':>12}")
    for name, (t, b) in results.items():
        print(f"{name:<12}{t:>12.1f}{b:>12}")

    return mlkem_bytes


# ---------------------------------------------------------------------------
# 2. Cost of one signature (sign + verify)
# ---------------------------------------------------------------------------

def section_2_signature(runs=1000):
    print("\n" + "=" * 62)
    print("2. Cost of one signature (sign + verify)")
    print("=" * 62)

    message = os.urandom(256)

    ed_key = ed25519.Ed25519PrivateKey.generate()
    ed_public = ed_key.public_key()

    def ed25519_sign_verify():
        signature = ed_key.sign(message)
        ed_public.verify(signature, message)

    with oqs.Signature("ML-DSA-44") as mldsa:
        mldsa_public = mldsa.generate_keypair()

        def mldsa_sign_verify():
            signature = mldsa.sign(message)
            assert mldsa.verify(message, signature, mldsa_public)

        sig_bytes = mldsa.details["length_signature"]
        ed_time = median_time_us(ed25519_sign_verify, runs)
        mldsa_time = median_time_us(mldsa_sign_verify, runs)

    print(f"Ed25519   : {ed_time:6.1f} us, signature = 64 bytes")
    print(f"ML-DSA-44 : {mldsa_time:6.1f} us, signature = {sig_bytes} bytes")

    return sig_bytes


# ---------------------------------------------------------------------------
# 3. Encrypting a real H.264 video with AES-256-GCM
#    A 20-second Full HD video at 8 Mb/s, cut into 1200-byte packets
#    (like live streaming), each packet encrypted on its own.
# ---------------------------------------------------------------------------

def section_3_video(path="video.mp4"):
    print("\n" + "=" * 62)
    print("3. Encrypting a real H.264 video with AES-256-GCM")
    print("=" * 62)

    if shutil.which("ffmpeg") is None:
        print("ffmpeg not found - section 3 skipped.")
        print("Install it with:  sudo apt install ffmpeg   (or brew install ffmpeg)")
        return

    # Create a real H.264 video with ffmpeg (1080p, 30 images/s, 8 Mb/s, 20 s)
    command = [
        "ffmpeg", "-loglevel", "error", "-y",
        "-f", "lavfi", "-i", "testsrc2=size=1920x1080:rate=30",
        "-t", "20",
        "-c:v", "libx264", "-preset", "veryfast",
        "-b:v", "8M", "-maxrate", "8M", "-bufsize", "16M",
        "-g", "30",
        path,
    ]
    print("Creating the test video with ffmpeg...")
    result = subprocess.run(command, capture_output=True, text=True)
    if result.returncode != 0:
        print("ffmpeg failed:", result.stderr.strip()[:500])
        return

    with open(path, "rb") as file:
        data = file.read()

    packets = [data[i:i + 1200] for i in range(0, len(data), 1200)]
    aes = AESGCM(os.urandom(32))                 # AES with a 256-bit key

    start = time.perf_counter()
    for number, packet in enumerate(packets):
        nonce = number.to_bytes(12, "big")       # a different nonce for every packet
        aes.encrypt(nonce, packet, None)
    seconds = time.perf_counter() - start

    print(f"Video size: {len(data)/1e6:.1f} MB, {len(packets)} packets")
    print(f"AES-256-GCM speed: {len(data)*8/seconds/1e9:.1f} Gb/s "
          f"(the video needs only 0.008 Gb/s)")
    print(f"Extra bytes per packet: 28 (12 nonce + 16 tag) = {28/1200*100:.2f} %")


# ---------------------------------------------------------------------------
# 4. Key-change rule: extra traffic
#    One post-quantum key change = hybrid exchange + ML-DSA-44 signature.
#    Extra traffic = 8*B / (R*T).  Rule: T >= 8*B / (0.01*R) keeps it below 1 %.
# ---------------------------------------------------------------------------

def section_4_key_change(mlkem_bytes, sig_bytes):
    print("\n" + "=" * 62)
    print("4. Key-change rule: extra traffic")
    print("=" * 62)

    B = 64 + mlkem_bytes + sig_bytes          # bytes of one key change
    print("One key change sends B =", B, "bytes\n")

    streams = {"HD video": 8e6, "4K video": 25e6, "XR": 100e6, "Hologram": 1e9}  # bit/s
    print(f"{'Stream':<10}{'every 1 s':>11}{'every 0.1 s':>13}"
          f"{'every 0.01 s':>14}{'min T (1 %)':>14}")
    for name, R in streams.items():
        overhead = [8 * B / (R * T) * 100 for T in (1, 0.1, 0.01)]
        T_min = 8 * B / (0.01 * R)
        print(f"{name:<10}{overhead[0]:>10.3f}%{overhead[1]:>12.2f}%"
              f"{overhead[2]:>13.1f}%{T_min:>12.3f} s")


# ---------------------------------------------------------------------------
# 5. BB84 simulation
#    Alice sends random bits in random bases; Bob measures in random bases;
#    they keep only the bits where the bases match. A spy who measures and
#    resends the photons creates about 25 % errors.
# ---------------------------------------------------------------------------

def bb84(rng, n_photons, spy=False, noise=0.0):
    alice_bits = rng.integers(0, 2, n_photons)
    alice_bases = rng.integers(0, 2, n_photons)
    bob_bases = rng.integers(0, 2, n_photons)
    bits, bases = alice_bits.copy(), alice_bases.copy()
    if spy:                                    # the spy measures in a random basis and resends
        spy_bases = rng.integers(0, 2, n_photons)
        bits = np.where(spy_bases == bases, bits, rng.integers(0, 2, n_photons))
        bases = spy_bases
    # Bob gets the right bit if he uses the same basis, otherwise a random bit
    bob_bits = np.where(bob_bases == bases, bits, rng.integers(0, 2, n_photons))
    bob_bits = bob_bits ^ (rng.random(n_photons) < noise)    # channel noise
    keep = alice_bases == bob_bases                          # sifting: same basis only
    error_rate = np.mean(alice_bits[keep] != bob_bits[keep])
    return keep.mean(), error_rate


def section_5_bb84(n_photons=200_000, seed=0):
    print("\n" + "=" * 62)
    print("5. BB84 simulation")
    print("=" * 62)

    rng = np.random.default_rng(seed)
    cases = [
        ("No spy, 1 % noise", False, 0.01),
        ("No spy, 5 % noise", False, 0.05),
        ("Spy (measure and resend)", True, 0.01),
    ]
    for case, spy, noise in cases:
        kept, err = bb84(rng, n_photons, spy, noise)
        print(f"{case:<28} bits kept = {kept*100:4.1f} %   "
              f"error rate = {err*100:4.1f} %")


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(
        description="Quantum-safe security of multimedia traffic in 6G - experiments"
    )
    parser.add_argument("--install", action="store_true",
                        help="install the Python libraries before running")
    parser.add_argument("--section", type=int, choices=[1, 2, 3, 4, 5],
                        help="run only one section (default: all)")
    parser.add_argument("--runs", type=int, default=1000,
                        help="number of timing runs (default: 1000)")
    parser.add_argument("--photons", type=int, default=200_000,
                        help="number of photons in the BB84 simulation")
    parser.add_argument("--video", default="video.mp4",
                        help="path of the test video created by ffmpeg")
    args = parser.parse_args()

    if args.install:
        install_packages()

    import_libraries()

    # Sections 1 and 2 give the sizes that section 4 needs. When a single
    # section is asked for, the missing sizes are read from the algorithms.
    mlkem_bytes = sig_bytes = None

    if args.section in (None, 1):
        mlkem_bytes = section_1_key_exchange(args.runs)
    if args.section in (None, 2):
        sig_bytes = section_2_signature(args.runs)
    if args.section in (None, 3):
        section_3_video(args.video)
    if args.section in (None, 4):
        if mlkem_bytes is None:
            with oqs.KeyEncapsulation("ML-KEM-768") as kem:
                mlkem_bytes = (kem.details["length_public_key"]
                               + kem.details["length_ciphertext"])
        if sig_bytes is None:
            with oqs.Signature("ML-DSA-44") as sig:
                sig_bytes = sig.details["length_signature"]
        section_4_key_change(mlkem_bytes, sig_bytes)
    if args.section in (None, 5):
        section_5_bb84(args.photons)

    print()


if __name__ == "__main__":
    main()
